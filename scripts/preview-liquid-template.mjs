import fs from 'node:fs';
import path from 'node:path';
import { build } from 'esbuild';
const root = path.resolve(import.meta.dirname, '..');
const source = path.join(root, 'design-assets/labs/liquid-glass-template');
const out = path.join(root, 'private_docs/design/liquid-glass-template');
fs.mkdirSync(out, { recursive: true });
await build({ entryPoints: [path.join(source, 'main.ts')], bundle: true, outfile: path.join(out, 'template.js'), platform: 'browser', format: 'iife', sourcemap: true, legalComments: 'eof' });
const styles = ['style-preview.css','component-gallery.css','layouts.css','additional-styles.css','showcase.css','scene-showcase.css','glass-showcase.css','liquid-showcase.css'];
fs.writeFileSync(path.join(out, 'template.css'), styles.map(file => fs.readFileSync(path.join(root, 'resources/visual-design', file), 'utf8')).join('\n'));
for (const file of ['index.html', 'lab.css']) fs.copyFileSync(path.join(source, file), path.join(out, file));
fs.copyFileSync(path.join(root, 'resources/visual-design/liquid-optics-LICENSE.txt'), path.join(out, 'liquid-optics-LICENSE.txt'));
console.log(out);
