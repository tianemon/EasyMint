/**
 * 上下文窗口 → 显示文案（唯一口径，聊天页各处共用）。
 *
 * 为什么要按「哪种进位能整除」分流：窗口值的两个来源用的不是同一个 K——
 *   预设表按标签写死：128K = 131072（128×1024）、256K = 262144，而 200K = 200000、400K = 400000 是十进制；
 *   厂商官方定义同样是 1024 的倍数（202752、204800、122880 等）。
 * 一律按 ÷1000 显示会让设置里选了 128K 的模型在聊天页显示成 131K，用户以为参数没生效。
 * 规则：值能被哪种进位整除就按哪种显示，显示值与用户配置时的标签对齐。
 */
export function formatTokenWindow(tokens: number): string {
  if (tokens >= 1_000_000) return `${Number((tokens / 1_000_000).toFixed(2))}M`;
  // 十进制优先：128000 同时是 125×1024，先判 1024 会显示成 125K
  if (tokens % 1000 === 0) return `${tokens / 1000}K`;
  if (tokens % 1024 === 0) return `${tokens / 1024}K`;
  return `${Math.floor(tokens / 1000)}K`;
}
